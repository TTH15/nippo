-- ============================================================
-- 車両の型式（世代）を持つ（2026-08-10）
--
-- ユーザー指摘: 「同じ車種でも年代によって全然形が違う」。
-- 軽バンは世代で見た目がはっきり変わる（例: エブリイ DA64V → DA17V）。
-- 3Dモデルを世代ごとに用意できるよう、**世代の識別子**を車両に持たせる。
--
-- 識別子は **型式**（DA17V / DR17V / S700V …）を使う:
--   ・車検証に必ず載っていて、現場で確実に読み取れる
--   ・年式より正確（年式は登録年でズレる）
--   ・OEM 関係も型式で追える（クリッパー DR17V ＝ エブリイ DA17V の OEM）
--
-- 3Dモデルの選択（vehicles.model_key）は「車種＋型式」から解決する。
-- 型式が分からない車は従来どおり車種だけで解決する（既定は現行世代）。
-- ============================================================

ALTER TABLE vehicles
  ADD COLUMN IF NOT EXISTS model_code text;

COMMENT ON COLUMN vehicles.model_code IS
  '型式（車検証の「型式」欄。例: DA17V）。世代の識別に使い、3Dモデルの出し分けの手がかりになる';
