-- ============================================================
-- org ごとの車体色パレット（2026-08-10）
--
-- 車体色は「白・グレー・黒」以外は各社の好み。毎回カラーピッカーで選ばせるのではなく、
-- **一度選んだ色を org に貯めて次回から選ぶだけ**にする（ユーザー要望）。
-- 実車の色は数種類に収束するので、パレットは自然に整う。
--
-- text[] で #RRGGBB を保持する。順序は「よく使う順」ではなく追加順（並べ替えは将来）。
-- ============================================================

ALTER TABLE organizations
  ADD COLUMN IF NOT EXISTS vehicle_body_colors text[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN organizations.vehicle_body_colors IS
  '車体色パレット（#RRGGBB の配列）。白・グレー・黒は既定で持つのでここには入れない';
