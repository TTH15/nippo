-- ============================================================
-- 氏名フリガナ（§2-1a 初期登録）。表記揺れ防止のため入力は姓・名分割だが、
-- 保存は「姓␣名」の合成（既存 name 列と同形式）。カナも「セイ␣メイ」で保存する。
-- 給与・口座名義（カナ）との突き合わせや名簿の読みに使う。
-- ============================================================

ALTER TABLE identities
  ADD COLUMN IF NOT EXISTS name_kana text;

COMMENT ON COLUMN identities.name_kana IS
  '氏名フリガナ（カタカナ・姓名は半角スペース区切り）。/join 申請時に本人入力';
